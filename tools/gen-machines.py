#!/usr/bin/env python3
"""Writes lib/machines.lua, the machine picker's groups, from the app.

Reads machineGroups in shared/.../model/MachineUi.kt for the groups and their
machines, and the group labels and machine_about_* lines from
strings/values/strings_machine_picker.xml. The app's lines are too long for
the norns screen, so SHORT below has a short one per machine; a machine
without one gets the app's line up to its first colon or comma, and a warning.

Usage: tools/gen-machines.py [APP_REPO] [OUT]
  APP_REPO defaults to ~/Projects/AndroidStudioProjects/Acidulous,
  OUT to lib/machines.lua next to this script.
"""
import os, re, sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
APP = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Projects/AndroidStudioProjects/Acidulous")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "lib", "machines.lua")
COMMON = os.path.join(APP, "shared/src/commonMain")
UI = os.path.join(COMMON, "kotlin/com/rm/acidulous/model/MachineUi.kt")
STRINGS = os.path.join(COMMON, "strings/values/strings_machine_picker.xml")

# about 16 letters each, to fit beside the name
SHORT = {
    "Reflux": "acid bass", "Trinity": "three osc poly", "Ratio": "six-op fm",
    "Cumulus": "spectrum pads", "Formulate": "chip, formulas",
    "Hexbeat": "small-box drums", "Genesis": "big drum box", "Resonance": "struck objects",
    "Dice": "loop slicer", "Forage": "sample drums", "Palm": "hand drums",
    "Hammer": "modelled piano", "Manual": "organ, rotary", "Tine": "bars and tines",
    "Filament": "modelled strings", "Fret": "electric guitar", "Sympath": "sitar, tanpura",
    "Brazen": "modelled brass", "Chanter": "bagpipes, gurdy", "Draw": "free reeds",
    "Timber": "woodwinds", "Tongue": "jaw harp",
    "Aviary": "birdsong", "Fathom": "water, weather",
    "Mosaic": "multisamples", "Pollen": "granular clouds", "Molt": "sung takes",
    "Divisi": "string ensemble", "Cipher": "vocoder", "Nexus": "modular", "Diction": "vocal synth", "Bias": "four-track",
}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    strings = {e.get("name"): (e.text or "") for e in ET.parse(STRINGS).getroot().iter("string")}
    text = open(UI, encoding="utf-8").read()
    body = text[text.index("val machineGroups"):]
    body = body[:body.index("\n    )\n")]
    groups = []
    for label, names, icon in re.findall(
            r'MachineGroup\(Res\.string\.(\w+),\s*listOf\(([^)]*)\)(?:\.sorted\(\))?,\s*GroupIcon\.(\w+)\)', body):
        machines = sorted(re.findall(r'"(\w+)"', names))
        groups.append((strings[label], icon.lower(), machines))
    if len(groups) != 8:
        print(f"gen-machines: {len(groups)} groups found, 8 expected", file=sys.stderr)
    lines = ["-- Generated by tools/gen-machines.py from the app's MachineUi.kt; don't edit.",
             "-- The machine picker's groups in the app's order {name, icon, machines},",
             "-- machines alphabetical in each group (the machine param follows this order),",
             "-- and a short line per machine.",
             "return {", "  groups = {"]
    about = {}
    for name, icon, machines in groups:
        lines.append(f"    {{name = {lua_str(name)}, icon = {lua_str(icon)}, machines = {{"
                     + ", ".join(lua_str(m) for m in machines) + "}},")
        for m in machines:
            line = SHORT.get(m)
            if not line:
                line = re.split(r"[:,]", strings.get("machine_about_" + m.lower(), ""))[0].lower()
                print(f"gen-machines: no short line for {m}, using '{line}'", file=sys.stderr)
            about[m] = line
    lines += ["  },", "  about = {"]
    for m in sorted(about):
        lines.append(f"    {m} = {lua_str(about[m])},")
    lines += ["  },", "}"]
    with open(OUT, "w") as f: f.write("\n".join(lines) + "\n")
    print(f"gen-machines: {sum(len(g[2]) for g in groups)} machines in {len(groups)} groups -> {OUT}")


if __name__ == "__main__":
    main()
