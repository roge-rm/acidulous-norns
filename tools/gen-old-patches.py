#!/usr/bin/env python3
"""Writes lib/oldpatches.lua, the bank patch names an older PSET's patch
indexes point at.

A PSET from before pN_patch_name holds only the patch's index into its
machine's bank. For each bank whose patch order differs between COMMIT (this
repo's commit with the older banks) and data/banks now, this lists the names
as they were at COMMIT, so the script can find the same patch by name.

Usage: tools/gen-old-patches.py COMMIT
"""
import os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "lib", "oldpatches.lua")
commit = sys.argv[1]


def names(text):
    out = []
    for line in text.splitlines():
        m = re.match(r'^patch\s+(?:"([^"]*)"|(\S+))', line)
        if m: out.append(m.group(1) if m.group(1) is not None else m.group(2))
    return out


def git(*args):
    return subprocess.run(["git", "-C", ROOT] + list(args), check=True, capture_output=True, text=True).stdout


old_files = [f for f in git("ls-tree", "--name-only", commit, "data/banks/").split() if f.endswith(".bank")]
changed = {}
for f in sorted(old_files):
    machine = os.path.basename(f)[:-5]
    if "." in machine: continue  # effect and modifier banks: PSETs never saved their index
    before = names(git("show", commit + ":" + f))
    path = os.path.join(ROOT, f)
    now = names(open(path).read()) if os.path.exists(path) else []
    if before != now: changed[machine] = before

short = git("rev-parse", "--short", commit).strip()
version = git("show", commit + ":third_party/acidulous/VERSION").split()[1][:8]
lua = lambda x: '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'
with open(OUT, "w") as f:
    f.write("-- Generated by tools/gen-old-patches.py %s. Never change it.\n" % short)
    f.write("-- The bank patch names, in bank order, of the machines whose banks have\n")
    f.write("-- changed order since the engine at %s, for PSETs that saved only a\n" % version)
    f.write("-- patch's index.\n")
    f.write("return {\n")
    for machine, before in changed.items():
        f.write("  %s = {\n" % machine)
        for n in before: f.write("    %s,\n" % lua(n))
        f.write("  },\n")
    f.write("}\n")
print("%d machine(s): %s -> %s" % (len(changed), ", ".join(changed), OUT))
